use std::net::IpAddr;

use agentkit_kernel::is_blocked;

fn ip(s: &str) -> IpAddr {
    s.parse().unwrap()
}

#[test]
fn blocked_v4_ranges() {
    for s in [
        "0.0.0.0",
        "0.1.2.3",
        "10.0.0.1",
        "10.255.255.255",
        "100.64.0.1",
        "100.127.255.254",
        "127.0.0.1",
        "127.255.0.9",
        "169.254.169.254",
        "172.16.0.1",
        "172.31.255.255",
        "192.0.0.8",
        "192.0.2.1",
        "192.168.1.1",
        "198.18.0.1",
        "198.19.255.255",
        "198.51.100.7",
        "203.0.113.9",
        "224.0.0.1",
        "239.255.255.250",
        "240.0.0.1",
        "255.255.255.255",
    ] {
        assert!(is_blocked(ip(s)), "{s}");
    }
}

#[test]
fn allowed_v4_neighbours() {
    for s in [
        "8.8.8.8",
        "1.1.1.1",
        "100.63.255.255",
        "100.128.0.1",
        "172.15.255.255",
        "172.32.0.1",
        "192.0.1.1",
        "192.167.0.1",
        "192.169.0.1",
        "198.17.0.1",
        "198.20.0.1",
        "198.51.101.1",
        "203.0.112.1",
        "223.255.255.255",
        "9.255.255.255",
        "11.0.0.1",
    ] {
        assert!(!is_blocked(ip(s)), "{s}");
    }
}

#[test]
fn blocked_v6_ranges_and_embedded_v4() {
    for s in [
        "::",
        "::1",
        "fc00::1",
        "fdff::1",
        "fe80::1",
        "febf::1",
        "ff02::1",
        "2001:db8::1",
        "::ffff:127.0.0.1",
        "::ffff:10.0.0.1",
        "::ffff:169.254.169.254",
        "::ffff:192.168.0.1",
        "::10.0.0.1",
        "::127.0.0.1",
        "64:ff9b::10.0.0.1",
        "64:ff9b::a9fe:a9fe",
        "64:ff9b::7f00:1",
        "2002:0a00:0001::1",
    ] {
        assert!(is_blocked(ip(s)), "{s}");
    }
}

#[test]
fn public_addresses_allowed() {
    for s in [
        "8.8.8.8",
        "2606:4700::1111",
        "2001:4860:4860::8888",
        "::ffff:8.8.8.8",
        "64:ff9b::808:808",
        "2001:db9::1",
        "fbff::1",
    ] {
        assert!(!is_blocked(ip(s)), "{s}");
    }
}

#[test]
fn transition_and_legacy_ranges_are_blocked() {
    for s in [
        "2001::1",
        "2001:0:4136:e378:8000:63bf:3fff:fdd2",
        "2001:0:ffff::1",
        "64:ff9b:1::1",
        "64:ff9b:1::808:808",
        "64:ff9b:1:ffff::1",
        "fec0::1",
        "fedf::1",
        "feff:ffff::1",
        "::ffff:0:10.0.0.1",
        "::ffff:0:127.0.0.1",
        "192.88.99.0",
        "192.88.99.255",
    ] {
        assert!(is_blocked(ip(s)), "{s}");
    }
}

#[test]
fn neighbours_of_new_ranges_stay_allowed() {
    for s in [
        "2001:1::1",
        "2000::1",
        "64:ff9b:2::1",
        "::ffff:0:8.8.8.8",
        "192.88.98.1",
        "192.88.100.1",
        "fe00::1",
    ] {
        assert!(!is_blocked(ip(s)), "{s}");
    }
}
